"""Write report/intent_results.tex: BANKING77 (Rami) and CLINC150 (Kristjan) side by side.

BANKING77 numbers are read with `git show` from branch rami at the pinned commit below
(intent_evidence.json, intent_significance.json); nothing on that branch is modified.
CLINC150 numbers come from clinc_evidence_test.json. No model calls.
"""
import json
import math
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent
RAMI_COMMIT = '0ed4ff6'  # origin/rami: "Document evidence-matched retrieval design and evaluation limits"


def rami(name):
    return json.loads(subprocess.run(['git', 'show', f'{RAMI_COMMIT}:{name}'], cwd=ROOT,
                                     capture_output=True, check=True).stdout)


def paired_ci(b, c, n):
    """Approximate 95% interval for a paired accuracy difference from discordant counts."""
    diff = (b - c) / n
    se = math.sqrt(b + c - (b - c) ** 2 / n) / n
    return diff - 1.96 * se, diff + 1.96 * se


def pvalue(p):
    if p < 1e-4:
        mantissa, exponent = f'{p:.1e}'.split('e')
        return rf'{mantissa}\times 10^{{{int(exponent)}}}'
    return f'{p:.2f}'


def main():
    be, bs = rami('intent_evidence.json'), rami('intent_significance.json')
    ce = json.loads((ROOT / 'clinc_evidence_test.json').read_text())
    bm, cm = be['metrics'], ce['policies']
    bmc = bs['exact_accuracy_mcnemar']
    b_lo, b_hi = paired_ci(bmc['candidate_only_correct'], bmc['agent_only_correct'], be['n'])
    ct = ce['accuracy_test']
    c_lo, c_hi = paired_ci(ct['with_jev_right_agent_wrong'], ct['with_jev_wrong_agent_right'], ce['n'])
    pct = lambda x: f'{100 * x:.2f}'
    macros = {
        'BkN': f"{be['n']:,}".replace(',', '{,}'), 'ClN': f"{ce['n']:,}".replace(',', '{,}'),
        'BkAgentAcc': pct(bm['agent']['accuracy']), 'BkJevLoopAcc': pct(bm['candidate_uncertified']['accuracy']),
        'BkJevAcc': pct(bm['jev']['accuracy']),
        'BkCostCut': f"{100 * be['candidate_targets']['cost_reduction']:.0f}",
        'BkCoverage': f"{100 * be['candidate_acceptance']['coverage']:.1f}",
        'BkUsedAcc': f"{100 * (1 - be['candidate_acceptance']['risk']):.1f}",
        'BkDiff': f"{100 * be['candidate_targets']['accuracy_difference']:.2f}",
        'BkLow': f'{100 * b_lo:.2f}', 'BkHigh': f'{100 * b_hi:.2f}',
        'BkOnlyJev': str(bmc['candidate_only_correct']), 'BkOnlyAgent': str(bmc['agent_only_correct']),
        'BkP': pvalue(bmc['pvalue']), 'BkCertUpper': f"{100 * be['certification']['one_sided_95_upper']:.2f}",
        'BkSpend': f"{be['research_spending']['accounted_usd']:.0f}",
        'ClAgentAcc': pct(cm['agent']['accuracy']), 'ClJevLoopAcc': pct(cm['with_jev']['accuracy']), 'ClJevAcc': pct(cm['jev']['accuracy']),
        'ClAgentOos': f"{100 * cm['agent']['oos_accuracy']:.1f}", 'ClJevLoopOos': f"{100 * cm['with_jev']['oos_accuracy']:.1f}",
        'ClJevOos': f"{100 * cm['jev']['oos_accuracy']:.1f}",
        'ClCostCut': f"{-100 * ce['cost_test']['relative_change']:.0f}",
        'ClCostLow': f"{-ce['cost_test']['bootstrap_95'][1]:.4f}", 'ClCostHigh': f"{-ce['cost_test']['bootstrap_95'][0]:.4f}",
        'ClCostT': f"{ce['cost_test']['t']:.0f}",
        'ClCoverage': f"{100 * ce['jev_coverage']['share']:.1f}", 'ClUsedAcc': f"{100 * ce['jev_coverage']['accuracy_when_used']:.1f}",
        'ClUsedOos': str(ce['jev_coverage']['oos_answered_by_jev']),
        'ClDiff': f"{100 * ct['accuracy_difference']:.2f}", 'ClLow': f'{100 * c_lo:.2f}', 'ClHigh': f'{100 * c_hi:.2f}',
        'ClOnlyJev': str(ct['with_jev_right_agent_wrong']), 'ClOnlyAgent': str(ct['with_jev_wrong_agent_right']),
        'ClP': pvalue(ct['p_value']), 'ClAgentFail': str(ce['failures']['agent']),
        'ClLatAgent': f"{ce['latency']['agent_p50_s']:.1f}", 'ClLatLoop': f"{ce['latency']['with_jev_p50_s']:.1f}",
        'ClSpend': f"{ce['spend']['accounted_usd']:.0f}",
    }
    rows = []
    for name, ev, m, keys, share in (
            (f"BANKING77 (77 intents, {be['n']:,} test; Rami)", be, bm, ('agent', 'candidate_uncertified', 'jev'), be['candidate_acceptance']['coverage']),
            (f"CLINC150 (150 intents + out-of-scope, {ce['n']:,} test)", ce, cm, ('agent', 'with_jev', 'jev'), ce['jev_coverage']['share'])):
        rows.append(rf"\multicolumn{{4}}{{l}}{{\emph{{{name.replace(',', '{,}')}}}}} \\")
        for key, label, sh in zip(keys, ('Agent alone (current)', 'Jev in the loop ($\\geq 0.96$)', 'Jev alone'), ('--', f'{100 * share:.1f}', '100')):
            cost = m[key]['mean_usd'] if 'mean_usd' in m[key] else m[key]['mean_cost_usd']
            rows.append(f"{label} & {100 * m[key]['accuracy']:.2f} & {cost:.5f} & {sh} \\\\")
        rows.append(r'\midrule')
    rows.pop()
    out = ['% Generated by build_intent_report.py; do not edit by hand.',
           f'% BANKING77 from origin/rami @ {RAMI_COMMIT}; CLINC150 from clinc_evidence_test.json.']
    out += [rf'\newcommand{{\{k}}}{{{v}}}' for k, v in macros.items()]
    out.append('\\newcommand{\\IntentRows}{\n' + '\n'.join(rows) + '\n}')
    (ROOT / 'report' / 'intent_results.tex').write_text('\n'.join(out) + '\n')
    print('\n'.join(f'{k} = {v}' for k, v in macros.items()))


if __name__ == '__main__':
    main()
